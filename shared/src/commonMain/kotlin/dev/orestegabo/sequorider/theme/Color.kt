internal fun sequoColorScheme(
    darkTheme: Boolean,
    contrast: SequoContrast,
): ColorScheme = when {
    darkTheme && contrast == SequoContrast.High -> darkHighContrastColorScheme
    darkTheme && contrast == SequoContrast.Medium -> darkMediumContrastColorScheme
    darkTheme -> darkColorScheme
    contrast == SequoContrast.High -> lightHighContrastColorScheme
    contrast == SequoContrast.Medium -> lightMediumContrastColorScheme
    else -> lightColorScheme
}
